use necrassrs::ExecutionOptions;

/// Server-controlled execution settings passed to every GraphQL request.
///
/// The values below are the NecrassRs defaults. GraphQL requests cannot
/// override them. Raising a limit admits larger requests and weakens the
/// protection it provides; rebuild and restart the service after editing.
/// See the `ExecutionOptions` API documentation for what each limit counts.
pub(crate) fn execution_options() -> ExecutionOptions {
    ExecutionOptions {
        // Whether clients may query `__schema` and `__type`.
        introspection: true,
        // Whether scalar and enum fields receive tracing spans.
        trace_scalars: false,
        // Repeated validation work allowed relative to the document size.
        validation_work_multiplier: 8,
        // Lexical tokens parsed from one request document.
        token_limit: 15_000,
        // Nesting of introspection list fields such as `fields` and `interfaces`.
        introspection_list_depth_limit: 2,
        // Values generated by schema introspection for one response.
        introspection_node_limit: 100_000,
        // Argument value nodes and string bytes passed to resolvers for one response.
        argument_work_limit: 4_000_000,
        // Fields executed for one response, including `__typename`.
        field_limit: 50_000,
        // List items completed for one response.
        list_item_limit: 50_000,
    }
}
